// Окно «правка не записана» при уходе с персонажа (мелочи 4б, п. 1, спека 2026-10-19-4b-minors.md,
// макет — вариант B). Текст и кнопки зависят от причины сбоя: «Повторить» есть, только когда
// повтор может помочь. Модуль чистый — его импортируют тесты в Node.
// error — вид сбоя очереди записи ('too_big' | 'network'); offline — нет сети (net-status.js);
// leave — куда уходит игрок: 'switch' (другой персонаж, новый, импорт, лист игрока у мастера) или
// 'logout' (выход из аккаунта); name — имя персонажа для показа (displayName), только как текст.
// → { message, note, retry }
const VERB = { switch: 'переключиться', logout: 'выйти' };

export function unsavedNotice({ error, offline, leave, name }) {
    const verb = VERB[leave] ?? VERB.switch;
    if (error === 'too_big') {
        return {
            message: 'Персонаж слишком большой и не записан.',
            note: `Сократите заметки или тексты предметов — тогда он запишется и можно будет ${verb}.`,
            retry: false,
        };
    }
    if (offline) {
        return {
            message: 'Нет связи — последние изменения ещё не записаны.',
            note: `Они запишутся сами, когда сеть вернётся. До этого ${verb} нельзя.`,
            retry: false,
        };
    }
    return {
        message: `Последние изменения «${name}» не сохранены.`,
        note: `Без них ${verb} нельзя — правка пропадёт.`,
        retry: true,
    };
}
